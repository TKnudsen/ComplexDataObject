/**
 * <p>
 * Enumerates the statistical characteristics that can describe the
 * uncertainty of a value, such as amount, lower/upper bound, lower/upper
 * quartile, median, and mean.
 * </p>
 */
public enum ValueUncertaintyCharacteristics {
	AMOUNT, LOWERBOUND, UPPERBOUND, LOWERQUARTILE, UPPERQUARTILE, MEDIAN, MEAN
}

package com.github.TKnudsen.ComplexDataObject.data.enums;

/**
 * <p>
 * Enumerates fuzzy/gradated boolean-like categories used to express uncertain
 * yes/no judgments, ranging from clear affirmation or negation to likely,
 * unlikely, unclear, or entirely missing information.
 * </p>
 *
 * @since 2015
 */
public enum FuzzyBooleanCategory {
	YES, NO, LIKELY, UNLIKELY, UNCLEAR, NO_INFORMATION
}
